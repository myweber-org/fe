pub struct DataProcessor {
    data: Vec<f64>,
}

impl DataProcessor {
    pub fn new() -> Self {
        DataProcessor { data: Vec::new() }
    }

    pub fn load_from_csv(&mut self, file_path: &str) -> Result<(), Box<dyn Error>> {
        let file = File::open(file_path)?;
        let reader = BufReader::new(file);

        for line in reader.lines() {
            let line = line?;
            if let Ok(value) = line.trim().parse::<f64>() {
                self.data.push(value);
            }
        }

        Ok(())
    }

    pub fn calculate_mean(&self) -> Option<f64> {
        if self.data.is_empty() {
            return None;
        }

        let sum: f64 = self.data.iter().sum();
        Some(sum / self.data.len() as f64)
    }

    pub fn calculate_standard_deviation(&self) -> Option<f64> {
        if self.data.len() < 2 {
            return None;
        }

        let mean = self.calculate_mean()?;
        let variance: f64 = self.data
            .iter()
            .map(|&x| (x - mean).powi(2))
            .sum::<f64>() / (self.data.len() - 1) as f64;

        Some(variance.sqrt())
    }

    pub fn get_summary(&self) -> String {
        let count = self.data.len();
        let mean_str = match self.calculate_mean() {
            Some(mean) => format!("{:.4}", mean),
            None => "N/A".to_string(),
        };
        let std_dev_str = match self.calculate_standard_deviation() {
            Some(std_dev) => format!("{:.4}", std_dev),
            None => "N/A".to_string(),
        };

        format!(
            "Data Summary:\n  Count: {}\n  Mean: {}\n  Standard Deviation: {}",
            count, mean_str, std_dev_str
        )
    }

    pub fn add_data_point(&mut self, value: f64) {
        self.data.push(value);
    }

    pub fn clear_data(&mut self) {
        self.data.clear();
    }
}

