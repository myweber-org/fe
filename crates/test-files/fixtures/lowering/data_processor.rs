#[derive(Debug, Serialize, Deserialize)]
pub struct DataRecord {
    id: u32,
    name: String,
    value: f64,
    tags: Vec<String>,
}

impl DataRecord {
    pub fn new(id: u32, name: String, value: f64, tags: Vec<String>) -> Self {
        DataRecord { id, name, value, tags }
    }

    pub fn validate(&self) -> Result<(), String> {
        if self.name.is_empty() {
            return Err("Name cannot be empty".to_string());
        }
        if self.value < 0.0 {
            return Err("Value must be non-negative".to_string());
        }
        if self.tags.len() > 10 {
            return Err("Too many tags, maximum is 10".to_string());
        }
        Ok(())
    }

    pub fn transform(&mut self, multiplier: f64) {
        self.value *= multiplier;
        self.name = self.name.to_uppercase();
    }
}

pub fn process_records(records: &mut Vec<DataRecord>) -> HashMap<String, f64> {
    let mut summary = HashMap::new();
    let mut total_value = 0.0;
    let mut valid_count = 0;

    for record in records.iter_mut() {
        if record.validate().is_ok() {
            record.transform(1.1);
            total_value += record.value;
            valid_count += 1;

            for tag in &record.tags {
                *summary.entry(tag.clone()).or_insert(0.0) += record.value;
            }
        }
    }

    if valid_count > 0 {
        summary.insert("average".to_string(), total_value / valid_count as f64);
    }

    summary.insert("total".to_string(), total_value);
    summary.insert("valid_count".to_string(), valid_count as f64);

    summary
}

