use pbkdf2::{
    password_hash::{
        rand_core::RngCore,
        SaltString, PasswordHasher, PasswordVerifier
    },
    Pbkdf2
};
use std::fs;
use std::io::{self, Write};

const SALT_LENGTH: usize = 16;
const NONCE_LENGTH: usize = 12;
const PBKDF2_ITERATIONS: u32 = 100_000;

pub struct FileEncryptor {
    cipher: Aes256Gcm,
}

impl FileEncryptor {
    pub fn new(password: &str) -> Result<Self, Box<dyn std::error::Error>> {
        let salt = SaltString::generate(&mut OsRng);
        let password_hash = Pbkdf2.hash_password(password.as_bytes(), &salt)?;
        let key_material = password_hash.hash.ok_or("Hash generation failed")?;
        
        let mut key_bytes = [0u8; 32];
        key_bytes.copy_from_slice(&key_material.as_bytes()[..32]);
        let key = Key::<Aes256Gcm>::from_slice(&key_bytes);
        
        Ok(Self {
            cipher: Aes256Gcm::new(key)
        })
    }

    pub fn encrypt_file(&self, input_path: &str, output_path: &str) -> io::Result<()> {
        let plaintext = fs::read(input_path)?;
        
        let mut nonce = [0u8; NONCE_LENGTH];
        OsRng.fill_bytes(&mut nonce);
        
        let ciphertext = self.cipher
            .encrypt(Nonce::from_slice(&nonce), plaintext.as_ref())
            .map_err(|e| io::Error::new(io::ErrorKind::Other, e))?;
        
        let mut output_data = Vec::with_capacity(NONCE_LENGTH + ciphertext.len());
        output_data.extend_from_slice(&nonce);
        output_data.extend_from_slice(&ciphertext);
        
        fs::write(output_path, output_data)
    }

    pub fn decrypt_file(&self, input_path: &str, output_path: &str) -> io::Result<()> {
        let encrypted_data = fs::read(input_path)?;
        
        if encrypted_data.len() < NONCE_LENGTH {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "File too short to contain nonce"
            ));
        }
        
        let nonce = &encrypted_data[..NONCE_LENGTH];
        let ciphertext = &encrypted_data[NONCE_LENGTH..];
        
        let plaintext = self.cipher
            .decrypt(Nonce::from_slice(nonce), ciphertext)
            .map_err(|e| io::Error::new(io::ErrorKind::Other, e))?;
        
        fs::write(output_path, plaintext)
    }
}

pub fn generate_key_file(password: &str, output_path: &str) -> io::Result<()> {
    let salt = SaltString::generate(&mut OsRng);
    let mut key_file = fs::File::create(output_path)?;
    
    writeln!(key_file, "PBKDF2-HMAC-SHA256")?;
    writeln!(key_file, "Iterations: {}", PBKDF2_ITERATIONS)?;
    writeln!(key_file, "Salt: {}", salt.as_str())?;
    
    Ok(())
}

